#!/usr/bin/env bash
# The realtime benchmark, informational (not a gate):
#
#   ./bench.sh [--res 720p,1440p] [--frames 30..60] [--avm-only]
#   ./bench.sh report --version <release> [--previous <old bench json>] [--not-run <why>] <part.json> ...
#
# The first form measures the one target this machine runs natively
# (linux-x86_64 on x86_64, linux-aarch64 on ARM64; BENCH_TARGET=<target>
# to name it) from dist/<target>/, and writes dist/bench/bench-<target>.json.
# Each clip is encoded in realtime mode with
#
#   --rt --cpu-used=9 --lag-in-frames=0 --end-usage=q --qp=160
#   --threads=4 --row-mt=1 --tile-columns=1   (+ --tune-content=screen for screen clips)
#
# and reports the keyframe time, the inter-frame mean and 95th percentile
# (avmenc's own per-frame times), the fps they imply, kbps, PSNR-Y (ffmpeg,
# on the decoded frames), and decode fps with 4 threads; then the same clips
# with the baselines through ffmpeg: x264 (ultrafast and veryfast,
# zerolatency), libaom realtime (cpu-used 10) and SVT-AV1 (preset 10, rtc).
# Clips are generated by ffmpeg (lavfi), so anyone can make the same ones:
# a page of code scrolling, a still desktop with a small changing region,
# testsrc2 motion; 1280x720 and 2560x1440, 60 frames (--frames) at 30 fps.
#
# The second form merges the parts of a release into bench-<release>.md and
# .json, flags changes over 10% against the previous release's JSON, and
# writes bench-summary.md for the release notes (build/release-notes.sh).
#
# Needs python3 and ffmpeg (with libx264, libaom, libsvtav1 for the
# baselines). DIST, WORK as for build.sh; OUT=<dir> instead of dist/bench.
set -euo pipefail

KIT=$(cd "$(dirname "$0")" && pwd)
# shellcheck source=build/lib.sh
. "$KIT/build/lib.sh"
OUT=${OUT:-$DIST/bench}

case ${1:-} in
    -h | --help) sed -n '2,29p' "$0"; exit 0 ;;
    report) shift; exec python3 "$KIT/build/bench.py" report --out "$OUT" "$@" ;;
esac

if [ -z "${BENCH_TARGET:-}" ]; then
    case $(uname -s)-$(uname -m) in
        Linux-x86_64) BENCH_TARGET=linux-x86_64 ;;
        Linux-aarch64 | Linux-arm64) BENCH_TARGET=linux-aarch64 ;;
        Darwin-arm64) BENCH_TARGET=macos-arm64 ;;
        Darwin-x86_64) BENCH_TARGET=macos-x86_64 ;;
        *) echo "bench.sh: no native target for $(uname -s) $(uname -m); BENCH_TARGET=<target>" >&2; exit 2 ;;
    esac
fi
[ -x "$DIST/$BENCH_TARGET/bin/avmenc" ] || {
    echo "bench.sh: no dist/$BENCH_TARGET; build it first" >&2; exit 2; }
# 126/127: the kernel cannot run it (another architecture)
rc=0; "$DIST/$BENCH_TARGET/bin/avmdec" --help > /dev/null 2>&1 || rc=$?
if [ "$rc" = 126 ] || [ "$rc" = 127 ]; then
    echo "bench.sh: dist/$BENCH_TARGET does not run on this machine" >&2; exit 2
fi
command -v ffmpeg > /dev/null || { echo "bench.sh needs ffmpeg" >&2; exit 2; }
exec python3 "$KIT/build/bench.py" run --target "$BENCH_TARGET" --dist "$DIST" \
    --work "$WORK" --out "$OUT" "$@"
